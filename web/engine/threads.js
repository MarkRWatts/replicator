const labOf = (t) => t.lab || (t.lab = rgbToLab(t.r, t.g, t.b));

function nearestIn(list, r, g, b) {
  const target = rgbToLab(r, g, b);
  let best = list[0], bestD = Infinity;
  for (const t of list) {
    const d = deltaE2000(target, labOf(t));
    if (d < bestD) { bestD = d; best = t; }
  }
  return best;
}

